    expect(sourceOnly).not.toContain('channel-header-tabs')
    expect(sourceOnly).not.toContain('model-draft-protocol-unified')
    expect(sourceOnly).not.toContain('model-draft-api-path-unified')
    expect(sourceOnly).not.toContain('provider-list-panel')
    expect(sourceOnly).not.toContain('data-testid="image-model-card"')
    expect(sourceOnly).not.toContain('data-testid="video-model-card"')
    expect(sourceOnly).not.toContain('data-testid="text-model-card"')
    expect(sourceOnly).not.toContain('isCreatingModel')
    expect(sourceOnly).not.toContain('modelCatalogOpen')
