import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

const settingsPagePath = resolve('src/pages/SettingsPage.vue')
const zhCnLocalePath = resolve('src/i18n/locales/zh-CN.ts')

// After the i18n refactor, Chinese UI copy lives in `src/i18n/locales/zh-CN.ts`
// and the .vue source now references it via `t('settings.*')`. To keep these
// "model contract" tests meaningful, split the file content into:
//   * `source`     — the .vue source plus the zh-CN catalog. Use for positive
//                    assertions (`toContain`) of UI strings and code shapes.
//   * `sourceOnly` — the .vue source alone. Use for negative assertions
//                    (`not.toContain`) that guard against regressing removed
//                    features/legacy copy.
